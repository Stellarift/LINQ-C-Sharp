CREATE TABLE Countries (
    Id        INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    Name      NVARCHAR(100) NOT NULL,
    Capital   NVARCHAR(100) NOT NULL,
    Population BIGINT NOT NULL,
    Area       FLOAT NOT NULL,
    Continent  NVARCHAR(50) NOT NULL
);
